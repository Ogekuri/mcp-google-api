#!/usr/bin/env bash
# /**
#  * @file build.sh
#  * @brief Generates the mcp-google-api release artifacts into `dist/` after cleaning every earlier build.
#  * @details Standalone, repeatable release build and obsolete-build cleaner (PKG-065, PKG-104) run from the
#  * repository root, in fail-fast order:
#  * 1. Preflight (PKG-067, PKG-068): Node.js >= 24, `node`, `npm`, `tar` on PATH and the
#  *    installed `node_modules/.bin/tsup` binary. Dependencies are never installed here.
#  * 2. Snapshot (PKG-073): a pre-existing `dist/` is copied to a private temp directory.
#  * 3. Obsolete-build cleanup (PKG-071, PKG-104, PKG-105, PKG-106, PKG-107): every `dist/` regular file
#  *    classified as generated by PKG-072 is removed, covering every artifact of every earlier build and
#  *    every package version number (including any `<name>-<version>.tgz` tarball); emptied ancestor
#  *    directories are pruned deepest-first, `dist/` itself only when empty, and non-generated entries
#  *    are never touched. An absent `dist/` is a successful no-op.
#  * 4. Compile (PKG-069): `npm run build` runs the generated-only pruner
#  *    (`tools/prune-generated-dist.mjs`, PKG-119) and then tsup (ESM runtime bundle and shared
#  *    chunks). tsup runs with `clean: false` so the committed release archive in `dist/` is never
#  *    wiped by the compiler (PKG-117, PKG-118).
#  * 5. Compile verification (PKG-069, PKG-074): `dist/cli.js` and `dist/index.js` must exist and be
#  *    non-empty; both must pass `node --check`; every relative import target of both entries must
#  *    exist and be non-empty.
#  * 6. Preservation (PKG-071, PKG-072): every non-generated snapshot file absent from the
#  *    new build is copied back into `dist/`. Generated files are never restored.
#  * 7. Pack (PKG-070, PKG-102): `npm pack --ignore-scripts --json --pack-destination <private work
#  *    directory>` (outside `dist/`, so the archive never contains itself). The tarball name MUST equal
#  *    `<name>-<version>.tgz` from `package.json`; the tarball MUST be non-empty and readable by `tar`,
#  *    then is moved to `dist/<name>-<version>.tgz` as a persistent release artifact (PKG-102).
#  * 8. Final cleanup (PKG-108, PKG-109): every intermediate artifact in `dist/` matching `*.tgz` of a
#  *    different version, `*.tsbuildinfo`, or `*.tmp` is removed and its emptied directories are pruned;
#  *    the current `dist/<name>-<version>.tgz` archive is preserved, then the private work directory is
#  *    removed; the run fails when any other intermediate artifact or the work directory survives.
#  * 9. Summary (PKG-074): path and byte size of every file in `dist/`.
#  * Failure semantics (PKG-073): any failing phase exits non-zero. The EXIT trap then
#  * restores the pre-run `dist/` snapshot, or removes `dist/` when none pre-existed, so a
#  * failed build never leaves a partial output set. Signals HUP, INT, and TERM exit through the same trap.
#  * @return Exit code 0 when every artifact is generated, verified, and the repository is left free of
#  *         intermediate artifacts; 1 on failure; 129, 130, 143 on HUP, INT, TERM.
#  * @pre Dependencies installed beforehand by the project package manager.
#  * @post On success `dist/` contains the verified release artifacts, including the release archive
#  *       `dist/<name>-<version>.tgz`, no other earlier-build artifact and no intermediate file survives,
#  *       and the private work directory is removed; on failure `dist/` equals its pre-run state.
#  * @note Runnable from any working directory (PKG-066); writes only under `dist/` and the OS temp directory.
#  * @satisfies PKG-065, PKG-066, PKG-067, PKG-068, PKG-069, PKG-070, PKG-071, PKG-072, PKG-073, PKG-074,
#  *            PKG-102, PKG-104, PKG-105, PKG-106, PKG-107, PKG-108, PKG-109
#  */
set -euo pipefail
cd "$(dirname "$0")/.."

readonly DIST_DIR="dist"
readonly MIN_NODE_MAJOR=24

# Snapshot state of dist/: unknown (no mutation allowed), absent, or snapshot (copy in WORKDIR).
PREVIOUS_STATE="unknown"
# 1 when the previous dist/ snapshot could not be restored; the work directory is then kept.
SNAPSHOT_RETAINED=0
WORKDIR=""

# /**
#  * @brief Prints one informational line on stdout with the build tag.
#  * @param message {string} Text printed after the tag.
#  * @return {void}
#  * @side_effect Writes to stdout.
#  */
log() {
  printf '[build] %s\n' "$*"
}

# /**
#  * @brief Aborts the build with a FAILED diagnostic naming the failed check.
#  * @details Writes `[build] FAILED: <message>` to stderr and exits 1; the EXIT trap then
#  * restores the previous `dist/` state (PKG-073). Complexity O(1).
#  * @param message {string} Diagnostic naming the missing prerequisite or failed step.
#  * @return {void} Never returns.
#  * @side_effect Terminates the process with exit code 1.
#  */
fail() {
  printf '[build] FAILED: %s\n' "$*" >&2
  exit 1
}

# /**
#  * @brief Verifies that a command is resolvable on PATH.
#  * @param name {string} Command name, e.g. `node`.
#  * @return {void} Returns when the command exists.
#  * @throws {exit 1} Via `fail` when the command is absent (PKG-067).
#  */
require_command() {
  if ! command -v "$1" >/dev/null 2>&1; then
    fail "required command not found on PATH: $1"
  fi
}

# /**
#  * @brief Verifies that every relative import target of one emitted ESM entry resolves.
#  * @details Runs an inline Node.js program (no repository file added, PKG-068) that scans the entry
#  * source for static `from "./x"`, side-effect `import "./x"`, and dynamic `import("./x")` specifiers
#  * beginning with `./` or `../`. Each specifier resolved against the entry directory MUST name an
#  * existing, non-empty regular file. Unresolved specifiers are printed by the program and echoed in the
#  * failure diagnostic. Complexity O(n) in source length plus one filesystem probe per specifier.
#  * @param entry {string} Emitted entry path, e.g. `dist/cli.js`.
#  * @return {void} Returns when every relative import target resolves.
#  * @throws {exit 1} Via `fail` naming the entry and the unresolved specifiers (PKG-069, PKG-074).
#  * @side_effect None; read-only inspection of the entry and its import targets.
#  */
verify_relative_imports() {
  local entry="$1"
  local program
  local unresolved=""
  program="$(cat <<'NODE_IMPORT_CHECK'
const { existsSync, readFileSync, statSync } = require("node:fs");
const { dirname, resolve } = require("node:path");
const entry = process.argv[1];
const pattern = /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)["'](\.{1,2}\/[^"']+)["']/g;
const unresolved = [];
for (const match of readFileSync(entry, "utf8").matchAll(pattern)) {
  const target = resolve(dirname(entry), match[1]);
  if (!existsSync(target) || !statSync(target).isFile() || statSync(target).size === 0) {
    unresolved.push(match[1]);
  }
}
if (unresolved.length > 0) {
  process.stdout.write(unresolved.join(" "));
  process.exit(1);
}
NODE_IMPORT_CHECK
)"
  if ! unresolved="$(node -e "$program" "$entry")"; then
    fail "unresolved relative import(s) in $entry: ${unresolved:-none reported}"
  fi
}

# /**
#  * @brief Classifies one dist-relative path as a generated build output.
#  * @details Pattern set `*.js`, `*.js.map`, `*.d.ts`, `*.d.ts.map`, `*.tgz`, `*.tsbuildinfo`,
#  * `*.tmp` (PKG-072). Matching is case-sensitive; pure, O(1).
#  * @param relative {string} Path relative to `dist/`.
#  * @return {number} 0 when generated; 1 when non-generated.
#  */
is_generated_output() {
  case "$1" in
    *.js | *.js.map | *.d.ts | *.d.ts.map | *.tgz | *.tsbuildinfo | *.tmp) return 0 ;;
    *) return 1 ;;
  esac
}

# /**
#  * @brief Classifies one dist-relative path as an intermediate build artifact.
#  * @details Intermediate subset of the PKG-072 generated set: `*.tgz`, `*.tsbuildinfo`, `*.tmp`.
#  * Callers MUST exempt the current release archive `dist/<name>-<version>.tgz` before applying this
#  * classifier: every other tarball version, build state file, and temporary file never belongs to the
#  * released artifact set and is removed by the final cleanup (PKG-108). Pure, O(1).
#  * @param relative {string} Path relative to `dist/`.
#  * @return {number} 0 when intermediate; 1 otherwise.
#  */
is_intermediate_output() {
  case "$1" in
    *.tgz | *.tsbuildinfo | *.tmp) return 0 ;;
    *) return 1 ;;
  esac
}

# /**
#  * @brief Copies the pre-run `dist/` directory into the private work directory.
#  * @details Sets PREVIOUS_STATE to `absent` when `dist/` does not exist, or to `snapshot` after
#  * a complete copy. A failed copy leaves PREVIOUS_STATE as `unknown`, so the trap never deletes
#  * a partially copied user directory (PKG-073). Runs before the cleanup phase so a failed build
#  * can restore the pre-run content.
#  * @return {void}
#  * @side_effect Creates `$WORKDIR/previous-dist` when `dist/` pre-exists.
#  * @throws {exit 1} Via `fail` when `dist` exists but is not a directory.
#  */
snapshot_previous_dist() {
  if [ -e "$DIST_DIR" ]; then
    if [ ! -d "$DIST_DIR" ]; then
      fail "$DIST_DIR exists but is not a directory"
    fi
    if ! cp -a "$DIST_DIR" "$WORKDIR/previous-dist"; then
      fail "could not snapshot pre-existing $DIST_DIR/"
    fi
    PREVIOUS_STATE="snapshot"
  else
    PREVIOUS_STATE="absent"
  fi
}

# /**
#  * @brief Restores `dist/` to its pre-run state.
#  * @details Removes `dist/`, then copies the snapshot back when one exists (PKG-073).
#  * Complexity O(size of dist).
#  * @return {number} 0 on success; 1 when removal or restoration fails.
#  * @side_effect Mutates `dist/` only.
#  */
restore_previous_dist() {
  if ! rm -rf "$DIST_DIR"; then
    return 1
  fi
  if [ "$PREVIOUS_STATE" = "snapshot" ]; then
    if ! cp -a "$WORKDIR/previous-dist" "$DIST_DIR"; then
      return 1
    fi
  fi
  return 0
}

# /**
#  * @brief EXIT trap: restores the previous state on failure and removes the work directory.
#  * @details Preserves the original exit status. Restore is attempted only when the snapshot
#  * state is known (PKG-073). The work directory is kept when a user snapshot could not be restored.
#  * Cleanup failure on a successful build turns the result into exit 1. Complexity O(size of dist)
#  * on the failure path.
#  * @return {void} Terminates with the resulting exit status.
#  * @side_effect Mutates `dist/` on failure; removes `$WORKDIR`.
#  */
on_exit() {
  local exit_status=$?
  trap - EXIT
  if [ "$exit_status" -ne 0 ] && [ "$PREVIOUS_STATE" != "unknown" ]; then
    # The snapshot is retained from the first destructive step until a complete restore (PKG-073).
    if [ "$PREVIOUS_STATE" = "snapshot" ]; then
      SNAPSHOT_RETAINED=1
    fi
    if restore_previous_dist; then
      SNAPSHOT_RETAINED=0
    else
      printf '[build] FAILED: could not restore the previous %s/ state (snapshot kept at %s)\n' "$DIST_DIR" "$WORKDIR" >&2
    fi
  fi
  if [ "$SNAPSHOT_RETAINED" -eq 0 ] && [ -n "$WORKDIR" ]; then
    if ! rm -rf "$WORKDIR"; then
      printf '[build] FAILED: could not remove temporary directory %s\n' "$WORKDIR" >&2
      if [ "$exit_status" -eq 0 ]; then
        exit_status=1
      fi
    fi
  fi
  exit "$exit_status"
}

# /**
#  * @brief Removes one directory when it is empty, tolerating non-empty directories.
#  * @details `rmdir` succeeds only on an empty directory; a directory still holding any entry is
#  * preserved by design because it carries non-generated content (PKG-106). A directory that is
#  * still empty after a failed `rmdir` reports a real removal error (PKG-107).
#  * Complexity O(1) plus one directory listing on the failure path.
#  * @param dir {string} Candidate directory path; ancestor of a removed artifact or `dist/` itself.
#  * @return {void}
#  * @throws {exit 1} Via `fail` when the directory is empty yet cannot be removed.
#  * @side_effect Removes `dir` when empty.
#  */
prune_emptied_dir() {
  local dir="$1"
  if [ ! -d "$dir" ]; then
    return 0
  fi
  if rmdir -- "$dir" 2>/dev/null; then
    log "pruned emptied directory: $dir"
    return 0
  fi
  if [ -z "$(ls -A "$dir")" ]; then
    fail "could not remove emptied directory: $dir"
  fi
  return 0
}

# /**
#  * @brief Cleanup phase: removes every generated artifact of earlier builds from `dist/`.
#  * @details First phase after the pre-run snapshot (PKG-104). Enumerates every `dist/` regular file
#  * into a NUL-delimited list inside the private work directory, removes each file classified as
#  * generated by PKG-072 — covering every artifact of every earlier build and every package version
#  * number, including any `<name>-<version>.tgz` tarball (PKG-071, PKG-105) — then prunes emptied
#  * ancestor directories deepest-first, `dist/` itself only when it ends up empty (PKG-106). Symlinks,
#  * directories, and every other non-generated entry are preserved. An absent `dist/` is a successful
#  * no-op; a non-directory `dist` entry, an enumeration failure, or a removal failure aborts with a
#  * FAILED diagnostic naming the failed entry (PKG-107). Complexity O(n) in `dist/` entry count.
#  * @return {void}
#  * @throws {exit 1} Via `fail` when enumeration or removal fails.
#  * @side_effect Removes generated files and emptied directories under `dist/` only.
#  */
clean_obsolete_build_artifacts() {
  if [ ! -e "$DIST_DIR" ]; then
    log "cleanup: nothing to remove, $DIST_DIR/ is absent"
    return 0
  fi
  if [ ! -d "$DIST_DIR" ]; then
    fail "$DIST_DIR exists but is not a directory"
  fi
  local file_list="$WORKDIR/obsolete-files.lst"
  if ! find "$DIST_DIR" -type f -print0 >"$file_list"; then
    fail "could not enumerate $DIST_DIR/ during the cleanup phase"
  fi
  local path
  local relative
  local parent
  local removed=0
  local removed_dirs=()
  while IFS= read -r -d '' path; do
    relative="${path#"$DIST_DIR"/}"
    if ! is_generated_output "$relative"; then
      continue
    fi
    if ! rm -f -- "$path"; then
      fail "could not remove generated artifact of an earlier build: $path"
    fi
    log "removed obsolete artifact: $path"
    removed=$((removed + 1))
    parent="$(dirname -- "$path")"
    while [ "$parent" != "$DIST_DIR" ] && [ "$parent" != "." ]; do
      removed_dirs+=("$parent")
      parent="$(dirname -- "$parent")"
    done
  done <"$file_list"
  if [ "${#removed_dirs[@]}" -gt 0 ]; then
    while IFS= read -r -d '' parent; do
      prune_emptied_dir "$parent"
    done < <(printf '%s\0' "${removed_dirs[@]}" | sort -rz | uniq -z)
  fi
  prune_emptied_dir "$DIST_DIR"
  log "cleanup: removed $removed obsolete generated artifact(s) of earlier builds from $DIST_DIR/"
}

# /**
#  * @brief Final cleanup: removes every intermediate artifact left by this build from `dist/`.
#  * @details Runs after every generation and verification step (PKG-108). Preserves the current release
#  * archive `dist/$TARBALL_NAME` (PKG-102), removes every other `dist/` regular file matching the
#  * intermediate subset `*.tgz`, `*.tsbuildinfo`, `*.tmp` for every package version number, prunes
#  * emptied ancestor directories and `dist/` itself when empty (PKG-106), and keeps every released
#  * artifact (`*.js` and its declaration/map siblings) plus every non-generated entry.
#  * Aborts with a FAILED diagnostic naming the failed entry when enumeration or removal fails
#  * (PKG-107). Complexity O(n) in `dist/` entry count.
#  * @return {void}
#  * @throws {exit 1} Via `fail` when `dist/` is missing or a removal fails.
#  * @side_effect Removes intermediate files and emptied directories under `dist/` only.
#  */
clean_intermediate_artifacts() {
  if [ ! -e "$DIST_DIR" ]; then
    log "final cleanup: nothing to remove, $DIST_DIR/ is absent"
    return 0
  fi
  if [ ! -d "$DIST_DIR" ]; then
    fail "$DIST_DIR exists but is not a directory"
  fi
  local file_list="$WORKDIR/intermediate-files.lst"
  if ! find "$DIST_DIR" -type f -print0 >"$file_list"; then
    fail "could not enumerate $DIST_DIR/ during the final cleanup"
  fi
  local path
  local relative
  local parent
  local removed=0
  local removed_dirs=()
  while IFS= read -r -d '' path; do
    relative="${path#"$DIST_DIR"/}"
    if [ -n "${TARBALL_NAME:-}" ] && [ "$relative" = "$TARBALL_NAME" ]; then
      log "final cleanup: preserved release archive: $path"
      continue
    fi
    if ! is_intermediate_output "$relative"; then
      continue
    fi
    if ! rm -f -- "$path"; then
      fail "could not remove intermediate build artifact: $path"
    fi
    log "removed intermediate artifact: $path"
    removed=$((removed + 1))
    parent="$(dirname -- "$path")"
    while [ "$parent" != "$DIST_DIR" ] && [ "$parent" != "." ]; do
      removed_dirs+=("$parent")
      parent="$(dirname -- "$parent")"
    done
  done <"$file_list"
  if [ "${#removed_dirs[@]}" -gt 0 ]; then
    while IFS= read -r -d '' parent; do
      prune_emptied_dir "$parent"
    done < <(printf '%s\0' "${removed_dirs[@]}" | sort -rz | uniq -z)
  fi
  prune_emptied_dir "$DIST_DIR"
  log "final cleanup: removed $removed intermediate artifact(s) from $DIST_DIR/"
}

# /**
#  * @brief Verifies that no intermediate artifact survives in `dist/`.
#  * @details Re-enumerates `dist/` after the final cleanup and aborts listing every path still
#  * matching the intermediate subset (PKG-109), ignoring the current release archive
#  * `dist/$TARBALL_NAME` which is a legitimate release artifact (PKG-102). Read-only. Complexity O(n)
#  * in entry count.
#  * @return {void}
#  * @throws {exit 1} Via `fail` naming the surviving paths.
#  * @side_effect Writes the verification list inside the private work directory.
#  */
verify_no_intermediate_artifacts() {
  local file_list="$WORKDIR/intermediate-verify.lst"
  local path
  local relative
  local remaining=""
  if ! find "$DIST_DIR" -type f -print0 >"$file_list"; then
    fail "could not enumerate $DIST_DIR/ during the final cleanup verification"
  fi
  while IFS= read -r -d '' path; do
    relative="${path#"$DIST_DIR"/}"
    if [ -n "${TARBALL_NAME:-}" ] && [ "$relative" = "$TARBALL_NAME" ]; then
      continue
    fi
    if is_intermediate_output "$relative"; then
      remaining="$remaining $path"
    fi
  done <"$file_list"
  if [ -n "$remaining" ]; then
    fail "intermediate artifact(s) survive the final cleanup:$remaining"
  fi
  log "final cleanup verified: no intermediate artifact remains in $DIST_DIR/"
}

# /**
#  * @brief Removes the private work directory and proves it is gone.
#  * @details Called only after every artifact was generated and verified, so no recovery snapshot is
#  * needed anymore (PKG-108, PKG-109). A failed removal or a surviving path aborts the build.
#  * Complexity O(size of the work directory).
#  * @return {void}
#  * @throws {exit 1} Via `fail` when the directory cannot be removed or still exists.
#  * @side_effect Removes `$WORKDIR`; clears the WORKDIR handle so the EXIT trap skips it.
#  */
remove_workdir() {
  if [ -z "$WORKDIR" ]; then
    return 0
  fi
  if ! rm -rf "$WORKDIR"; then
    fail "could not remove temporary work directory $WORKDIR"
  fi
  if [ -e "$WORKDIR" ]; then
    fail "temporary work directory survives the final cleanup: $WORKDIR"
  fi
  log "final cleanup: temporary work directory removed"
  WORKDIR=""
}

# /**
#  * @brief Restores every non-generated snapshot entry missing from the freshly built `dist/`.
#  * @details Enumerates all snapshot entries (NUL-delimited list, no pipeline status masking).
#  * Skips only regular files matching generated patterns (PKG-072); recreates directories, copies
#  * symlinks and other non-generated entries, and aborts on destination-type collisions so the
#  * EXIT trap restores the original snapshot rather than discarding user content (PKG-071, PKG-073).
#  * Complexity O(n) in snapshot entry count.
#  * @return {void}
#  * @side_effect Creates files and directories under `dist/`.
#  * @throws {exit 1} Via `fail` when enumeration or copy fails.
#  */
preserve_non_generated_entries() {
  local snapshot_root="$WORKDIR/previous-dist"
  local file_list="$WORKDIR/previous-files.lst"
  local source
  local relative
  local destination
  if [ "$PREVIOUS_STATE" != "snapshot" ]; then
    return 0
  fi
  if ! find "$snapshot_root" -mindepth 1 -print0 >"$file_list"; then
    fail "could not enumerate the previous $DIST_DIR/ snapshot"
  fi
  while IFS= read -r -d '' source; do
    relative="${source#"$snapshot_root"/}"
    destination="$DIST_DIR/$relative"
    if [ -f "$source" ] && [ ! -L "$source" ] && is_generated_output "$relative"; then
      continue
    fi
    if [ -d "$source" ] && [ ! -L "$source" ]; then
      if [ -L "$destination" ] || { [ -e "$destination" ] && [ ! -d "$destination" ]; }; then
        fail "non-generated directory conflicts with build output: $destination"
      fi
      if [ ! -d "$destination" ] && ! mkdir -p "$destination"; then
        fail "could not preserve non-generated directory $destination"
      fi
      log "preserved non-generated directory: $destination"
      continue
    fi
    if [ -e "$destination" ] || [ -L "$destination" ]; then
      fail "non-generated entry conflicts with build output: $destination"
    fi
    if ! mkdir -p "$(dirname "$destination")" || ! cp -a "$source" "$destination"; then
      fail "could not preserve non-generated entry $destination"
    fi
    log "preserved non-generated entry: $destination"
  done <"$file_list"
}

trap on_exit EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

# Preflight (PKG-067, PKG-068).
require_command node
require_command npm
require_command tar
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
if [ "$NODE_MAJOR" -lt "$MIN_NODE_MAJOR" ]; then
  fail "Node.js >= $MIN_NODE_MAJOR required, found major $NODE_MAJOR"
fi
if [ ! -x "node_modules/.bin/tsup" ]; then
  fail "dependencies not installed: node_modules/.bin/tsup missing; install dependencies with 'npm ci' first"
fi

WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/mcp-google-api-build.XXXXXX")"
snapshot_previous_dist
log "preflight passed (node $(node -p 'process.versions.node'), dist/ state: $PREVIOUS_STATE)"

# Obsolete-build cleanup (PKG-071, PKG-104, PKG-105, PKG-106, PKG-107).
clean_obsolete_build_artifacts

# Compile (PKG-069).
log "compile: npm run build"
npm run build

for artifact in cli.js index.js; do
  if [ ! -s "$DIST_DIR/$artifact" ]; then
    fail "compile output missing or empty: $DIST_DIR/$artifact"
  fi
done
node --check "$DIST_DIR/cli.js"
node --check "$DIST_DIR/index.js"
verify_relative_imports "$DIST_DIR/cli.js"
verify_relative_imports "$DIST_DIR/index.js"
log "compile verified: $DIST_DIR/cli.js, $DIST_DIR/index.js, relative imports resolved"

# Preservation of non-generated dist/ entries (PKG-071, PKG-072).
preserve_non_generated_entries

# Pack (PKG-070, PKG-102): pack into a private work directory, verify, then publish into dist/.
rm -f -- "$DIST_DIR"/*.tgz
PACK_DIR="$WORKDIR/pack"
mkdir -p "$PACK_DIR"
log "pack: npm pack --ignore-scripts --pack-destination <private work directory>"
PACK_JSON="$(npm pack --ignore-scripts --json --pack-destination "$PACK_DIR")"
TARBALL_NAME="$(printf '%s' "$PACK_JSON" | node -e 'let raw = ""; process.stdin.setEncoding("utf8"); process.stdin.on("data", (chunk) => { raw += chunk; }); process.stdin.on("end", () => { const entries = JSON.parse(raw); if (!Array.isArray(entries) || typeof entries[0]?.filename !== "string") { process.exit(1); } process.stdout.write(entries[0].filename); });')"
EXPECTED_TARBALL="$(node -p 'const pkg = require("./package.json"); pkg.name + "-" + pkg.version + ".tgz";')"
if [ "$TARBALL_NAME" != "$EXPECTED_TARBALL" ]; then
  fail "tarball name mismatch: npm produced '$TARBALL_NAME', expected '$EXPECTED_TARBALL'"
fi
if [ ! -s "$PACK_DIR/$TARBALL_NAME" ]; then
  fail "tarball missing or empty: $PACK_DIR/$TARBALL_NAME"
fi
if ! tar -tzf "$PACK_DIR/$TARBALL_NAME" >/dev/null; then
  fail "tarball not readable by tar: $PACK_DIR/$TARBALL_NAME"
fi
if ! mv -f -- "$PACK_DIR/$TARBALL_NAME" "$DIST_DIR/$TARBALL_NAME"; then
  fail "could not place the release archive in $DIST_DIR/: $TARBALL_NAME"
fi
if [ ! -s "$DIST_DIR/$TARBALL_NAME" ]; then
  fail "release archive missing or empty: $DIST_DIR/$TARBALL_NAME"
fi
log "pack verified: $DIST_DIR/$TARBALL_NAME (release artifact)"

# Final cleanup (PKG-108, PKG-109): no intermediate artifact and no work directory may survive.
clean_intermediate_artifacts
verify_no_intermediate_artifacts
remove_workdir

# Summary (PKG-074).
log "SUCCESS: release artifacts generated in $DIST_DIR/:"
find "$DIST_DIR" -type f -print0 | sort -z | while IFS= read -r -d '' artifact; do
  printf '[build]   %s (%s bytes)\n' "$artifact" "$(wc -c <"$artifact")"
done
log "repository left clean: no intermediate build artifact, no temporary work directory"
exit 0
