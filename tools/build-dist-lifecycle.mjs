#!/usr/bin/env node
/**
 * @file build-dist-lifecycle.mjs
 * @brief Atomic `dist/` orchestration of the `build`/`prepare` lifecycles: preflight, prune, compile, restore-on-failure.
 * @details Single orchestration point of `package.json` `scripts.build` (which `prepare` reuses). Phases, in order:
 *          1. Preflight (PKG-120): `node_modules/.bin/tsup` MUST exist; otherwise the run aborts non-zero
 *             BEFORE removing or writing any `dist/` entry, so a toolchain-less invocation never destroys
 *             the tracked runtime bundle (`dist/cli.js`, `dist/index.js`, shared chunks).
 *          2. Snapshot (PKG-121): every `dist/` regular file classified as generated by PKG-072 except
 *             `*.tgz` is copied into a private OS-temp directory, recording its relative path.
 *          3. Prune (PKG-119): the generated-output pruner `tools/prune-generated-dist.mjs` runs as a
 *             child process; every `*.tgz` archive and every non-generated entry survives (PKG-117, PKG-118).
 *          4. Compile (PKG-069): the installed `tsup` compiler runs as a child process with
 *             `tsup.config.ts` `clean: false`, so the committed release archive is never wiped (PKG-117).
 *          5. Recovery (PKG-121, PKG-122): a non-zero prune or compile phase restores the snapshot files
 *             byte-identically, removes generated outputs absent from the snapshot, emits one `FAILED`
 *             diagnostic naming the failing phase, and propagates the failing exit code.
 *          6. Success: the private snapshot directory is removed and the run exits 0 (PKG-074 semantics of
 *             the caller `scripts/build.sh` are untouched: the script still drives `npm run build`).
 *          The private snapshot directory is always removed before exit, on success and on failure.
 * @requires node:child_process (spawnSync), node:fs, node:os, node:path, node:url
 * @satisfies PKG-069, PKG-117, PKG-118, PKG-119, PKG-120, PKG-121, PKG-122
 * @note Writes only under `dist/` and the OS temp directory. No network access, no dependency
 *       installation, no publication. stdout carries `[build-dist-lifecycle]` diagnostics only;
 *       failures write to stderr.
 * @warning Never bypass this script from `package.json` `scripts.build`: the direct pruner and the
 *          direct compiler invocations cannot restore `dist/` after a failed compile (PKG-121).
 * @see tools/prune-generated-dist.mjs, tsup.config.ts, scripts/build.sh, package.json `scripts.build`
 */

import { spawnSync } from "node:child_process";
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readdirSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Repository root resolved from this script location, so the lifecycle is cwd-independent (PKG-066).
 * @type {string}
 */
const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

/**
 * Build output directory owned by both the compiler and the release build script.
 * @type {string}
 */
const DIST_DIR = join(PROJECT_ROOT, "dist");

/**
 * Tracked generated-output pruner executed as the pre-compile phase (PKG-119).
 * @type {string}
 */
const PRUNER_SCRIPT = join(PROJECT_ROOT, "tools", "prune-generated-dist.mjs");

/**
 * Installed compiler binary; its absence aborts the lifecycle before any `dist/` mutation (PKG-120).
 * @type {string}
 */
const TSUP_BIN = join(PROJECT_ROOT, "node_modules", ".bin", process.platform === "win32" ? "tsup.cmd" : "tsup");

/**
 * Generated-output suffixes of the PKG-072 classification minus `*.tgz`.
 * @details The `*.tgz` archive class is deliberately absent: the committed release archive is a
 *          tracked release artifact that the lifecycle never removes (PKG-117, PKG-118).
 * @type {readonly string[]}
 */
const GENERATED_SUFFIXES = Object.freeze([".js", ".js.map", ".d.ts", ".d.ts.map", ".tsbuildinfo", ".tmp"]);

/**
 * Archive suffix preserved by every lifecycle phase regardless of the packaged version.
 * @type {string}
 */
const ARCHIVE_SUFFIX = ".tgz";

/**
 * Diagnostic tag prefixed to every emitted line.
 * @type {string}
 */
const TAG = "[build-dist-lifecycle]";

/**
 * @brief Writes one informational line on stdout.
 * @details Concatenates the tag, the supplied fragments, and a newline.
 * @param {...string} fragments {string} Diagnostic fragments joined by one space.
 * @return {void}
 * @side_effect Writes one stdout line.
 */
function log(...fragments) {
  process.stdout.write(`${TAG} ${fragments.join(" ")}\n`);
}

/**
 * @brief Writes one failure line on stderr.
 * @details Prefixes the diagnostic with the tag and `FAILED:` so callers and CI greps can assert on
 *          it without parsing free text. Complexity O(n) in message length.
 * @param {string} message {string} Diagnostic naming the failing prerequisite or phase.
 * @return {void}
 * @side_effect Writes one stderr line.
 */
function reportFailure(message) {
  process.stderr.write(`${TAG} FAILED: ${message}\n`);
}

/**
 * @brief Classifies one dist-relative path as a snapshotted generated output.
 * @details Pure suffix classification: true when the name ends with a PKG-072 generated suffix and
 *          does not end with the archive suffix. Complexity O(k) with k suffixes.
 * @param {string} relativePath {string} Path relative to `dist/`.
 * @return {boolean} True when the entry is a generated output restored on failure (PKG-121).
 * @satisfies PKG-072, PKG-121
 */
function isGeneratedOutput(relativePath) {
  if (relativePath.endsWith(ARCHIVE_SUFFIX)) {
    return false;
  }
  return GENERATED_SUFFIXES.some((suffix) => relativePath.endsWith(suffix));
}

/**
 * @brief Recursively collects every generated output of one `dist/` subtree.
 * @details Walks the subtree without following symbolic links and appends the relative POSIX path of
 *          every regular file accepted by `isGeneratedOutput`. Complexity O(n) in entry count.
 * @param {string} directory {string} Absolute directory currently scanned.
 * @param {string} relativePrefix {string} Path prefix relative to `dist/` ("" for the root).
 * @param {string[]} out {string[]} Accumulator of relative paths.
 * @return {void}
 * @side_effect Appends to `out` only; never mutates the filesystem.
 * @satisfies PKG-121
 */
function collectGeneratedOutputs(directory, relativePrefix, out) {
  for (const entry of readdirSync(directory)) {
    const absolutePath = join(directory, entry);
    const relativePath = relativePrefix === "" ? entry : `${relativePrefix}/${entry}`;
    const stats = lstatSync(absolutePath);
    if (stats.isSymbolicLink()) {
      continue;
    }
    if (stats.isDirectory()) {
      collectGeneratedOutputs(absolutePath, relativePath, out);
      continue;
    }
    if (stats.isFile() && isGeneratedOutput(relativePath)) {
      out.push(relativePath);
    }
  }
}

/**
 * @brief Reports whether `dist/` exists as a usable directory.
 * @details A missing `dist/` is a valid fresh-checkout state; a non-directory `dist` entry is an
 *          unusable state that MUST abort the lifecycle before any mutation. Complexity O(1).
 * @return {"absent" | "directory" | "invalid"} Observed `dist/` state.
 * @satisfies PKG-120, PKG-121
 */
function inspectDistDirectory() {
  try {
    const stats = lstatSync(DIST_DIR);
    return stats.isDirectory() ? "directory" : "invalid";
  } catch {
    return "absent";
  }
}

/**
 * @brief Copies the generated `dist/` outputs into a private snapshot directory.
 * @details Creates `snapshotRoot` and copies every relative path reported by
 *          `collectGeneratedOutputs`, preserving the directory layout. Complexity O(size of the
 *          generated outputs).
 * @param {string} snapshotRoot {string} Absolute snapshot directory to create.
 * @param {string[]} relativePaths {string[]} Generated outputs relative to `dist/`.
 * @return {void}
 * @throws {Error} Propagated from filesystem copy operations.
 * @side_effect Creates directories and files under `snapshotRoot`.
 * @satisfies PKG-121
 */
function writeSnapshot(snapshotRoot, relativePaths) {
  for (const relativePath of relativePaths) {
    const destination = join(snapshotRoot, relativePath);
    mkdirSync(dirname(destination), { recursive: true });
    cpSync(join(DIST_DIR, relativePath), destination);
  }
}

/**
 * @brief Restores the snapshot generated outputs and drops generated outputs absent from it.
 * @details Removes every generated output currently present in `dist/` that the snapshot does not
 *          hold (partial compile output or pruned leftovers), then copies every snapshot file back,
 *          recreating directories on demand. `*.tgz` archives and non-generated entries are never
 *          touched (PKG-117, PKG-118). Complexity O(size of the generated outputs).
 * @param {string} snapshotRoot {string} Absolute snapshot directory produced by `writeSnapshot`.
 * @param {string[]} relativePaths {string[]} Snapshot generated outputs relative to `dist/`.
 * @return {void}
 * @throws {Error} Propagated from filesystem operations.
 * @side_effect Mutates generated entries under `dist/` only.
 * @satisfies PKG-121, PKG-122
 */
function restoreSnapshot(snapshotRoot, relativePaths) {
  const kept = new Set(relativePaths);
  if (inspectDistDirectory() === "directory") {
    const current = [];
    collectGeneratedOutputs(DIST_DIR, "", current);
    for (const relativePath of current) {
      if (kept.has(relativePath)) {
        continue;
      }
      rmSync(join(DIST_DIR, relativePath), { force: true });
      log(`removed partial generated output: ${relativePath}`);
    }
  }
  for (const relativePath of relativePaths) {
    const destination = join(DIST_DIR, relativePath);
    mkdirSync(dirname(destination), { recursive: true });
    cpSync(join(snapshotRoot, relativePath), destination);
    log(`restored generated output: ${relativePath}`);
  }
}

/**
 * @brief Runs one lifecycle child process with inherited stdio.
 * @details Spawns `command[0]` with the remaining tokens from the repository root; `shell` is
 *          enabled only on win32 so the npm `.cmd` shim single-file binaries resolve. Complexity
 *          O(1) plus the child run time.
 * @param {string} label {string} Phase label used in the failure diagnostic.
 * @param {readonly string[]} command {readonly string[]} Executable plus arguments.
 * @return {number} Child exit code; 1 when the child could not be spawned or reported no status.
 * @side_effect Inherits the caller stdio, so child output reaches the invoking shell.
 * @satisfies PKG-119, PKG-121
 */
function runPhase(label, command) {
  const result = spawnSync(command[0], command.slice(1), {
    cwd: PROJECT_ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (result.error) {
    reportFailure(`${label} phase could not start: ${result.error.message}`);
    return 1;
  }
  if (result.status === null) {
    reportFailure(`${label} phase terminated without an exit status`);
    return 1;
  }
  return result.status;
}

/**
 * @brief Runs the full `build`/`prepare` lifecycle atomically over `dist/`.
 * @details Preflight (PKG-120) -> snapshot (PKG-121) -> prune (PKG-119) -> compile (PKG-069) ->
 *          restore-on-failure (PKG-121, PKG-122) -> snapshot removal. Every failure path leaves the
 *          pre-run generated `dist/` outputs in place, so the tracked runtime bundle is never absent
 *          after a run (PKG-122). Complexity O(size of `dist/`) plus two child processes.
 * @return {number} Exit code: 0 when prune and compile succeed; the failing child status otherwise
 *         (1 when a phase could not start).
 * @satisfies PKG-069, PKG-117, PKG-118, PKG-119, PKG-120, PKG-121, PKG-122
 * @post On success `dist/` holds the freshly compiled outputs; on failure it holds the pre-run
 *       generated outputs byte-identically; in both cases the private snapshot directory is gone.
 */
function runBuildLifecycle() {
  if (!existsSync(TSUP_BIN)) {
    reportFailure(
      "node_modules/.bin/tsup missing; dist/ was not modified, install dependencies with 'npm ci' first (PKG-120)",
    );
    return 1;
  }
  const distState = inspectDistDirectory();
  if (distState === "invalid") {
    reportFailure(`${DIST_DIR} is not a directory; dist/ was not modified (PKG-120)`);
    return 1;
  }
  const snapshotPaths = [];
  const snapshotRoot = mkdtempSync(join(tmpdir(), "mcp-google-api-dist-snapshot-"));
  try {
    if (distState === "directory") {
      collectGeneratedOutputs(DIST_DIR, "", snapshotPaths);
      writeSnapshot(snapshotRoot, snapshotPaths);
      log(`snapshot: ${snapshotPaths.length} generated output(s) captured from ${DIST_DIR}/`);
    } else {
      log("snapshot: dist/ is absent, nothing to capture");
    }
    const pruneCode = runPhase("prune", [process.execPath, PRUNER_SCRIPT]);
    if (pruneCode !== 0) {
      restoreSnapshot(snapshotRoot, snapshotPaths);
      reportFailure(`prune phase exited with status ${pruneCode}; dist/ restored (PKG-121)`);
      return pruneCode;
    }
    const compileCode = runPhase("compile", [TSUP_BIN]);
    if (compileCode !== 0) {
      restoreSnapshot(snapshotRoot, snapshotPaths);
      reportFailure(`compile phase exited with status ${compileCode}; dist/ restored (PKG-121)`);
      return compileCode;
    }
    log("lifecycle completed: dist/ holds the freshly compiled outputs");
    return 0;
  } finally {
    rmSync(snapshotRoot, { recursive: true, force: true });
  }
}

process.exitCode = runBuildLifecycle();
